export const getLanguageOption = (langId: string): LanguageOption => {
  return (
    SUPPORTED_LANGUAGES.find((l) => l.id === langId) ||
    SUPPORTED_LANGUAGES.find((l) => l.id === 'en')!
  );
};

export const t = (key: string, langId = 'en'): string => {
  const langDict = TRANSLATIONS[langId] || TRANSLATIONS['en'];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  return TRANSLATIONS['en'][key] || key;
};
